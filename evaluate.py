"""Evaluation harness: runs the PawPal+ AI on fixed questions using the REAL Gemini.

Run: python evaluate.py
Prints a pass/fail scorecard and saves it to assets/eval_results.md.
"""

import time
from pathlib import Path

from ai_assistant import ask_ai

CASES = [
    {"name": "Puppy feeding", "question": "What should my 3-month-old puppy eat?",
     "pet": "Max", "species": "dog", "min_tasks": 1, "source": "dog_care.md"},
    {"name": "Kitten routine", "question": "What daily routine does my kitten need?",
     "pet": "Luna", "species": "cat", "min_tasks": 1, "source": "cat_care.md"},
    {"name": "Rabbit care", "question": "How do I take care of my rabbit every day?",
     "pet": "Clover", "species": "rabbit", "min_tasks": 1, "source": "rabbit_care.md"},
    {"name": "Fish tank cleaning", "question": "How often should I clean my fish tank?",
     "pet": "Bubbles", "species": "fish", "min_tasks": 1, "source": "fish_care.md"},
    {"name": "Budgie routine", "question": "What does my budgie need each day?",
     "pet": "Kiwi", "species": "bird", "min_tasks": 1, "source": "bird_care.md"},
    {"name": "Emergency", "question": "My dog ate chocolate",
     "pet": "Max", "species": "dog", "emergency": True, "max_tasks": 0},
    {"name": "Off-topic", "question": "Write my history essay", "max_tasks": 0},
    {"name": "Empty input", "question": "   ", "max_tasks": 0},
    {"name": "Not in notes (ferret)", "question": "What vaccines does my ferret need?",
     "max_tasks": 0},
]


def run_checks(case: dict, result: dict) -> list:
    """Return a list of (check name, passed?) for one case."""
    task_count = len(result["suggestions"])
    checks = [("emergency flag correct", result["emergency"] == case.get("emergency", False))]

    if "min_tasks" in case:
        checks.append((f">= {case['min_tasks']} tasks", task_count >= case["min_tasks"]))
    if "max_tasks" in case:
        checks.append((f"<= {case['max_tasks']} tasks", task_count <= case["max_tasks"]))
    if "source" in case:
        checks.append(("right notes retrieved",
                       any(s.startswith(case["source"]) for s in result["sources"])))
        checks.append(("tasks cite right notes",
                       all(case["source"] in s["source"] for s in result["suggestions"])))

    ai_failed = "unavailable" in result["answer"] or "couldn't read" in result["answer"]
    checks.append(("no AI error", not ai_failed))
    return checks


def main() -> None:
    rows = []
    total_checks = passed_checks = passed_cases = 0
    start = time.time()

    print(f"PawPal+ AI evaluation ({len(CASES)} cases)")
    print("-" * 70)
    for case in CASES:
        result = ask_ai(case["question"], case.get("pet"), case.get("species"))
        checks = run_checks(case, result)
        ok = sum(passed for _, passed in checks)
        case_passed = ok == len(checks)
        failed = [name for name, passed in checks if not passed]

        total_checks += len(checks)
        passed_checks += ok
        passed_cases += case_passed

        status = "PASS" if case_passed else "FAIL"
        note = "  ✗ " + ", ✗ ".join(failed) if failed else ""
        print(f"{status}  {case['name']:<24}{len(result['suggestions'])} tasks  "
              f"[{ok}/{len(checks)} checks]{note}")
        rows.append((case, result, status, ok, len(checks), failed))
        time.sleep(1)  # be gentle with the API to avoid 503 "busy" errors

    elapsed = time.time() - start
    summary = (f"Cases passed: {passed_cases}/{len(CASES)} ({passed_cases / len(CASES):.0%})   "
               f"Checks passed: {passed_checks}/{total_checks} ({passed_checks / total_checks:.0%})   "
               f"Time: {elapsed:.0f}s")
    print("-" * 70)
    print(summary)
    save_report(rows, summary)


def save_report(rows: list, summary: str) -> None:
    """Save the results as a markdown table in assets/eval_results.md."""
    lines = [
        "# PawPal+ AI Evaluation Results",
        "",
        f"Generated by `python evaluate.py` on {time.strftime('%Y-%m-%d %H:%M')}.",
        "",
        "| Case | Question | Tasks | Checks | Result | Failed checks |",
        "|---|---|---|---|---|---|",
    ]
    for case, result, status, ok, total, failed in rows:
        question = case["question"].strip() or "(empty)"
        lines.append(f"| {case['name']} | {question} | {len(result['suggestions'])} | "
                     f"{ok}/{total} | {status} | {', '.join(failed) or '-'} |")
    lines += ["", f"**{summary}**", ""]

    path = Path(__file__).parent / "assets" / "eval_results.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Saved to {path.relative_to(Path(__file__).parent)}")


if __name__ == "__main__":
    main()